"""Flatten benchmarks/results/results.json (per-source, per-engine detail)
into the row-per-(field, engine) schema the frontend dashboard reads:
frontend/public/data/benchmark_results.json

Run after run_benchmarks.py. Never hand-edit the output — regenerate it.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS_PATH = ROOT / "benchmarks" / "results" / "results.json"
OUT_PATH = ROOT / "frontend" / "public" / "data" / "benchmark_results.json"


def flatten(rows):
    flat = []
    for row in rows:
        base = {"field": row["field"], "source": row["source"], "n": row["n"], "detection_map50": row.get("detection_map50")}
        engines_present = [k[: -len("_ocr_exact_match")] for k in row if k.endswith("_ocr_exact_match")]
        if not engines_present:
            flat.append(base)
            continue
        for engine in engines_present:
            flat.append(
                {
                    "field": f"{row['field']} ({engine})",
                    "source": row["source"],
                    "n": row.get("n_ocr", row["n"]),
                    "detection_map50": row.get("detection_map50") if engine == engines_present[0] else None,
                    "ocr_exact_match": row.get(f"{engine}_ocr_exact_match"),
                    "cer": row.get(f"{engine}_cer"),
                }
            )
    return flat


def main():
    if not RESULTS_PATH.exists():
        raise SystemExit("run benchmarks/run_benchmarks.py first")
    results = json.loads(RESULTS_PATH.read_text())

    out = {
        "generated": True,
        "note": f"Generated by benchmarks/export_for_dashboard.py from {RESULTS_PATH.relative_to(ROOT)}",
        "real": flatten(results["real"]),
        "synthetic": flatten(results["synthetic"]),
        "review_rate_over_time": [],
    }
    OUT_PATH.write_text(json.dumps(out, indent=2))
    print(f"[done] wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
